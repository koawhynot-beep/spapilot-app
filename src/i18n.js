const DICTS = { en: EN, id: ID };

const LangContext = createContext({ lang: 'en', setLang: () => {}, t: (k) => k });

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = localStorage.getItem(LANG_KEY);
    return DICTS[saved] ? saved : 'en';
  });

  const setLang = useCallback((next) => {
    if (!DICTS[next]) return;
    localStorage.setItem(LANG_KEY, next);
    setLangState(next);
  }, []);

  // Falls back to English, then to the key itself, so a gap in the Indonesian
  // dictionary degrades to readable English instead of showing 'tab.sell'.
  const t = useCallback(
    (key) => DICTS[lang][key] ?? EN[key] ?? key,
    [lang]
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

// For the few places that cannot use the hook: the crash screen, which
// renders outside the provider by definition, and anything running before
// React has mounted. Reads the stored choice directly.
export function tStatic(key) {
  let lang = 'en';
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (DICTS[saved]) lang = saved;
  } catch { /* private mode: English is a fine default */ }
  return DICTS[lang][key] ?? EN[key] ?? key;
}

export const useLang = () => useContext(LangContext);
export const useT = () => useContext(LangContext).t;
